def _lessons(spec):
    """Expand one unit spec into three ordered lessons (mission-led rhythm)."""
    vocab = spec["vocab"]
    grammar = spec["grammar"]
    dialogue = spec["dialogue"]
    exercises = spec["exercises"]
    chunks = [vocab[:2], vocab[2:4], vocab[4:]]
    if not chunks[-1]:
        chunks = chunks[:2]
    titles = ["Discover", "Build", "Use it"]
    titles_fr = ["Découvrir", "Construire", "Mettre en pratique"]
    lessons = []
    for index, words in enumerate(chunks):
        ex = exercises[index % len(exercises):index % len(exercises) + 1] if exercises else []
        lesson = Lesson(
            id=f"{spec['id']}-l{index + 1}",
            title=f"{titles[index]}: {spec['title']}",
            titleFr=f"{titles_fr[index]} : {spec['titleFr']}",
            description=f"{spec['description']} Step {index + 1} of the mission.",
            objectives=[spec["outcomes"][min(index, len(spec["outcomes"]) - 1)]],
            vocabulary=[VocabItem(fr, en, example=example) for fr, en, example in words],
            grammar=[GrammarRule(
                title=grammar[0], explanation=grammar[1],
                examples=[GrammarExample(grammar[2], grammar[3])],
                tip=grammar[4] if len(grammar) > 4 else None,
            )] if grammar and index < 2 else [],
            dialogue=[DialogueLine(*line) for line in dialogue] if index == 1 else [],
            exercises=[
                Exercise(id=f"{spec['id']}-l{index + 1}-e{n}", type=item[0], prompt=item[1],
                         options=item[2], answer=item[3], explanation=item[4])
                for n, item in enumerate(ex, 1)
            ],
            estimatedMinutes=25,
            skillTags=list(spec["modes"]),
            transferTask=f"{spec['capstone']} (step {index + 1}, unscored)",
            selfCheck=spec["criteria"] if index == 2 else [spec["outcomes"][0]],
            descriptor_ids=spec["descriptors"],
            communicative_modes=list(spec["modes"]),
            skill_evidence=[f"Step {index + 1} practice artefact"],
            provenance=PROVENANCE,
        )
        lessons.append(lesson)
    return lessons


def build_attributed_catalog():
    catalog = {}
    for level, specs in SPECS.items():
        units = [
            Unit(
                id=spec["id"], title=spec["title"], titleFr=spec["titleFr"],
                theme=spec["theme"], description=spec["description"],
                lessons=_lessons(spec), outcomes=spec["outcomes"],
                skillTags=list(spec["modes"]), capstone=spec["capstone"],
                capstoneCriteria=spec["criteria"], descriptor_ids=spec["descriptors"],
                communicative_modes=list(spec["modes"]), provenance=PROVENANCE,
            )
            for spec in specs
        ]
        catalog[level] = Course(
            level=level, title=f"Parlez {level} — attributed mission path",
            book="Parlez original content", description=f"Mission-led {level} practice built from attributed sources.",
            cefrDescription=f"{level} can-do inspired outcomes; practice, not certification.",
            color="#7C2D3F", units=units,
            levelOutcomes=[outcome for spec in specs for outcome in spec["outcomes"]],
            version=PROVENANCE.version, contentStatus="published_unattested",
            framework=FRAMEWORK, descriptor_ids=sorted({d for spec in specs for d in spec["descriptors"]}),
            provenance=PROVENANCE,
        )
    return catalog


