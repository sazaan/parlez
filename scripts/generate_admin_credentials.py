#!/usr/bin/env python3
"""Generate environment values for Parlez's dedicated admin login.

Run locally with the app dependencies installed:
    python scripts/generate_admin_credentials.py --env-file .env

When called by run.sh, the app image runs this script and writes credentials
straight to the host's ignored .env file. Keep that file private.
"""

import argparse
import getpass
import os
import re
import secrets
import tempfile
from pathlib import Path

import bcrypt
import pyotp


ADMIN_KEYS = ("ADMIN_USERNAME", "ADMIN_PASSWORD_HASH", "ADMIN_TOTP_SECRET", "ADMIN_SESSION_SECRET")


def _validate_username(username: str) -> str:
    username = username.strip()
    if not re.fullmatch(r"[A-Za-z0-9_.@-]{1,80}", username):
        raise SystemExit("Use a username of 1–80 letters, numbers, dots, underscores, @ signs, or hyphens.")
    return username


def _env_assignment(key: str, value: str) -> str:
    """Quote values with shell-significant characters (notably bcrypt's '$')."""
    if re.fullmatch(r"[A-Za-z0-9_./:@+-]+", value):
        return f"{key}={value}"
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"{key}='{escaped}'"


def write_admin_values(env_path: str | Path, values: dict[str, str]) -> Path:
    """Atomically upsert admin values, preserving the rest of the .env file."""
    path = Path(env_path).expanduser().resolve(strict=True)
    if not path.is_file():
        raise SystemExit(f"Environment file is not a regular file: {path}")
    if set(values) != set(ADMIN_KEYS):
        raise ValueError("Exactly the four required admin credentials must be provided.")

    existing = path.read_text(encoding="utf-8")
    result: list[str] = []
    seen: set[str] = set()
    for line in existing.splitlines():
        match = re.match(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
        key = match.group(1) if match else None
        if key not in values:
            result.append(line)
        elif key not in seen:
            result.append(_env_assignment(key, values[key]))
            seen.add(key)
        # Drop duplicate definitions so Compose and dotenv cannot disagree.

    missing = [key for key in ADMIN_KEYS if key not in seen]
    if missing:
        if result and result[-1].strip():
            result.append("")
        result.append("# Admin credentials generated by scripts/generate_admin_credentials.py.")
        result.extend(_env_assignment(key, values[key]) for key in missing)

    content = "\n".join(result).rstrip("\n") + "\n"
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as temporary_file:
            temporary_file.write(content)
            temporary_file.flush()
            os.fsync(temporary_file.fileno())
        os.replace(temporary_name, path)
        os.chmod(path, 0o600)
        directory_fd = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temporary_name):
            os.unlink(temporary_name)
    return path


def _generate_values() -> tuple[dict[str, str], str]:
    username = _validate_username(input("Admin username [parlez-admin]: ") or "parlez-admin")
    password = getpass.getpass("Admin password (at least 16 characters): ")
    if len(password) < 16:
        raise SystemExit("Use a password of at least 16 characters.")
    if len(password.encode("utf-8")) > 72:
        raise SystemExit("bcrypt passwords must be at most 72 bytes; choose a shorter password.")
    confirmation = getpass.getpass("Confirm admin password: ")
    if not secrets.compare_digest(password, confirmation):
        raise SystemExit("Passwords did not match.")

    totp_secret = pyotp.random_base32()
    values = {
        "ADMIN_USERNAME": username,
        "ADMIN_PASSWORD_HASH": bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt(rounds=12)).decode("ascii"),
        "ADMIN_TOTP_SECRET": totp_secret,
        "ADMIN_SESSION_SECRET": secrets.token_urlsafe(48),
    }
    totp_uri = pyotp.TOTP(totp_secret).provisioning_uri(name=username, issuer_name="Parlez Admin")
    return values, totp_uri


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--env-file",
        help="write credentials into this existing env file instead of printing secret values",
    )
    args = parser.parse_args()

    values, totp_uri = _generate_values()
    if args.env_file:
        env_path = write_admin_values(args.env_file, values)
        print(f"Admin credentials saved to {env_path.name} with file permissions restricted to the owner.")
        print(f"Admin username: {values['ADMIN_USERNAME']}")
        print("Enroll this TOTP URI in your authenticator app (it contains the TOTP secret):")
        print(totp_uri)
        print("Keep the generated password and authenticator private; restart Parlez after setup.")
        return

    print("\nAdd these values to the backend .env (never to frontend code):\n")
    for key in ADMIN_KEYS:
        print(_env_assignment(key, values[key]))
    print("ADMIN_SESSION_TTL_MINUTES=15")
    print("\nEnroll this TOTP URI in your authenticator app (the URI contains the TOTP secret):")
    print(totp_uri)
    print("\nKeep the .env file private and restart Parlez after updating it.")


if __name__ == "__main__":
    main()
